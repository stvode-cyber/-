/**
 * 根据账单标题推断分类
 *
 * @param title 账单标题（如"午餐"、"打车去机场"）
 * @param type  账单类型（income 时优先返回"工资"）
 * @returns 推断的分类名称，无法匹配时返回"其他"
 */
export function classifyBillCategory(title: string, type?: string): string {
  // 收入类型优先匹配工资类关键词，未命中则直接返回"工资"（收入最常见的分类）
  if (type === 'income') {
    for (const rule of CATEGORY_RULES) {
      if (rule.category === '工资' && rule.keywords.some((kw) => title.includes(kw))) {
        return '工资'
      }
    }
    return '工资'
  }

  // 支出类型：按规则顺序匹配，先命中先返回
  const lowerTitle = title.toLowerCase()
  for (const rule of CATEGORY_RULES) {
    if (rule.keywords.some((kw) => lowerTitle.includes(kw.toLowerCase()))) {
      return rule.category
    }
  }
  return '其他'
}
